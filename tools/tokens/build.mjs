#!/usr/bin/env node
// Writes the design tokens (ADR 0028, ADR 0051) from core/shared/design/tokens.json to:
//   core/shared/design/tokens.css   CSS custom properties (--c-*, --map-*, --t-*, --r-*, --s-*)
//   web/ui/app/tokens.gen.ts        the same CSS as a string, for the Worker's stylesheet
//   android/outage/.../ui/Tokens.kt Compose colours, map colours, spacing and shape
// One source, so the website and the phone can never drift. One light palette (ADR 0053). Dependency-free.
// `node tools/tokens/build.mjs` writes; `--check` exits 1 when a file is stale.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const paths = {
  json: join(root, 'core/shared/design/tokens.json'),
  css: join(root, 'core/shared/design/tokens.css'),
  ts: join(root, 'web/ui/app/tokens.gen.ts'),
  kt: join(root, 'android/outage/app/src/main/kotlin/app/outage/ui/Tokens.kt'),
};

export const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
// The system font: Roboto on Android and ChromeOS, San Francisco on Apple, Segoe UI on Windows. Nothing to download.
const FONT = "Roboto,system-ui,-apple-system,'Segoe UI','Helvetica Neue',Arial,sans-serif";

export function render(t) {
  const vars = [
    ...Object.entries(t.colors).map(([k, v]) => `--c-${k}:${v};`),
    ...Object.entries(t.map).map(([k, v]) => `--map-${k}:${v};`),
    ...Object.entries(t.shape).map(([k, v]) => `--r-${k}:${v}px;`),
    ...t.space.map((n) => `--s-${n}:${n}px;`),
    ...Object.entries(t.type).map(([k, [size, line, weight]]) => `--t-${k}:${weight} ${size / 16}rem/${line / 16}rem ${FONT};`),
    `--font:${FONT};`,
  ];
  const css = `:root{${vars.join('')}color-scheme:light}`;
  const cssFile = `/* Generated by tools/tokens/build.mjs from tokens.json. Do not edit. */\n${css}\n`;
  const ts =
    `// Generated by tools/tokens/build.mjs from core/shared/design/tokens.json. Do not edit.\n` +
    `export const TOKENS_CSS = ${JSON.stringify(css)};\n` +
    `export const THEME_COLOUR = ${JSON.stringify(t.colors.paper)};\n`;
  const colours = (name, set) =>
    `    object ${name} {\n${Object.entries(set)
      .map(([k, v]) => `        val ${camel(k)} = Color(${argb(v)})`)
      .join('\n')}\n    }\n`;
  const kt =
    `package app.outage.ui\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n` +
    `/** Generated by tools/tokens/build.mjs from core/shared/design/tokens.json (ADR 0028, ADR 0051). Do not edit. */\n` +
    `object Tokens {\n${colours('Colors', t.colors)}\n${colours('Map', t.map)}\n` +
    t.space.map((n) => `    val space${n} = ${n}.dp`).join('\n') +
    '\n' +
    Object.entries(t.shape)
      .map(([k, n]) => `    val corner${camel(`-${k}`)} = ${n}.dp`)
      .join('\n') +
    '\n}\n';
  return { css: cssFile, ts, kt };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(JSON.parse(readFileSync(paths.json, 'utf8')));
  const check = process.argv.includes('--check');
  let stale = false;
  for (const k of ['css', 'ts', 'kt']) {
    if (check) {
      if (!existsSync(paths[k]) || readFileSync(paths[k], 'utf8') !== out[k]) {
        console.error(`stale: ${paths[k]}`);
        stale = true;
      }
    } else writeFileSync(paths[k], out[k]);
  }
  process.exit(stale ? 1 : 0);
}
