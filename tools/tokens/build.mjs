#!/usr/bin/env node
// Writes the design tokens (ux-redesign task 2, ADR 0028) from packages/shared/design/tokens.json to:
//   packages/shared/design/tokens.css, workers/api/src/web/app/tokens.gen.ts, apps/android/.../ui/Tokens.kt.
// Dependency-free. `node tools/tokens/build.mjs` writes; `--check` exits 1 when a file is stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const paths = {
  json: join(root, 'packages/shared/design/tokens.json'),
  css: join(root, 'packages/shared/design/tokens.css'),
  ts: join(root, 'workers/api/src/web/app/tokens.gen.ts'),
  kt: join(root, 'apps/android/app/src/main/kotlin/app/outage/ui/Tokens.kt'),
};

const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^nodata$/, 'noData');
const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
const decl = (set) => Object.entries(set).map(([k, v]) => `--${k}:${v};`).join('');

export function render(t) {
  const css =
    `/* Generated by tools/tokens/build.mjs from tokens.json. Do not edit. */\n` +
    `:root{${decl(t.dark)}color-scheme:dark}\n` +
    `@media(prefers-color-scheme:light){:root{${decl(t.light)}color-scheme:light}}\n`;
  const ts =
    `// Generated by tools/tokens/build.mjs from packages/shared/design/tokens.json. Do not edit.\n` +
    `export const TOKENS_DARK = ${JSON.stringify(decl(t.dark))};\n` +
    `export const TOKENS_LIGHT = ${JSON.stringify(decl(t.light))};\n`;
  const block = (name, set) =>
    `    object ${name} {\n${Object.entries(set)
      .map(([k, v]) => `        val ${camel(k)} = Color(${argb(v)})`)
      .join('\n')}\n    }\n`;
  const kt =
    `package app.outage.ui\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n` +
    `/** Generated by tools/tokens/build.mjs from packages/shared/design/tokens.json (ADR 0028). Do not edit. */\n` +
    `object Tokens {\n${block('Dark', t.dark)}\n${block('Light', t.light)}\n` +
    t.space.map((n) => `    val space${n} = ${n}.dp`).join('\n') + '\n' +
    Object.entries(t.radius)
      .map(([k, n]) => `    val radius${k[0].toUpperCase()}${k.slice(1)} = ${n}.dp`)
      .join('\n') + '\n}\n';
  return { css, ts, kt };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(JSON.parse(readFileSync(paths.json, 'utf8')));
  const check = process.argv.includes('--check');
  let stale = false;
  for (const k of ['css', 'ts', 'kt']) {
    if (check) {
      if (!existsSync(paths[k]) || readFileSync(paths[k], 'utf8') !== out[k]) {
        console.error(`stale: ${paths[k]}`);
        stale = true;
      }
    } else writeFileSync(paths[k], out[k]);
  }
  process.exit(stale ? 1 : 0);
}
