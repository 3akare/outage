#!/usr/bin/env node
// Writes the Material 3 design tokens (ADR 0028, ADR 0048) from core/shared/design/tokens.json to:
//   core/shared/design/tokens.css   CSS custom properties (--md-sys-*), light by default, dark by media query
//   web/ui/app/tokens.gen.ts        the same CSS as a string, for the Worker's stylesheet
//   android/outage/.../ui/Tokens.kt Compose colours, map colours, spacing and shape
// One source, so the website and the phone can never drift. Dependency-free.
// `node tools/tokens/build.mjs` writes; `--check` exits 1 when a file is stale.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const paths = {
  json: join(root, 'core/shared/design/tokens.json'),
  css: join(root, 'core/shared/design/tokens.css'),
  ts: join(root, 'web/ui/app/tokens.gen.ts'),
  kt: join(root, 'android/outage/app/src/main/kotlin/app/outage/ui/Tokens.kt'),
};

export const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
const FONT = "Roboto,'Google Sans',system-ui,-apple-system,'Segoe UI',sans-serif";

function cssVars(mode, t) {
  const colours = Object.entries(t[mode]).map(([k, v]) => `--md-sys-color-${k}:${v};`);
  const map = Object.entries(t.map[mode]).map(([k, v]) => `--md-map-${k}:${v};`);
  return colours.join('') + map.join('');
}

function cssStatic(t) {
  const shape = Object.entries(t.shape).map(([k, v]) => `--md-sys-shape-corner-${k}:${v}px;`);
  const space = t.space.map((n) => `--md-space-${n}:${n}px;`);
  const type = Object.entries(t.type).map(
    ([k, [size, line, weight]]) => `--md-sys-typescale-${k}:${weight} ${size / 16}rem/${line / 16}rem ${FONT};`,
  );
  return shape.join('') + space.join('') + type.join('') + `--md-font:${FONT};`;
}

export function render(t) {
  // Light first, dark when the system asks for it. data-theme on <html> wins over the system setting.
  const css =
    `:root{${cssStatic(t)}${cssVars('light', t)}color-scheme:light}` +
    `@media(prefers-color-scheme:dark){:root:not([data-theme=light]){${cssVars('dark', t)}color-scheme:dark}}` +
    `:root[data-theme=dark]{${cssVars('dark', t)}color-scheme:dark}`;
  const cssFile = `/* Generated by tools/tokens/build.mjs from tokens.json. Do not edit. */\n${css}\n`;
  const ts =
    `// Generated by tools/tokens/build.mjs from core/shared/design/tokens.json. Do not edit.\n` +
    `export const TOKENS_CSS = ${JSON.stringify(css)};\n` +
    `export const THEME_LIGHT = ${JSON.stringify(t.light.surface)};\n` +
    `export const THEME_DARK = ${JSON.stringify(t.dark.surface)};\n`;
  const colours = (name, set) =>
    `    object ${name} {\n${Object.entries(set)
      .map(([k, v]) => `        val ${camel(k)} = Color(${argb(v)})`)
      .join('\n')}\n    }\n`;
  const kt =
    `package app.outage.ui\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n` +
    `/** Generated by tools/tokens/build.mjs from core/shared/design/tokens.json (ADR 0028, ADR 0048). Do not edit. */\n` +
    `object Tokens {\n${colours('Light', t.light)}\n${colours('Dark', t.dark)}\n` +
    `${colours('MapLight', t.map.light)}\n${colours('MapDark', t.map.dark)}\n` +
    t.space.map((n) => `    val space${n} = ${n}.dp`).join('\n') +
    '\n' +
    Object.entries(t.shape)
      .map(([k, n]) => `    val corner${camel(`-${k}`)} = ${n}.dp`)
      .join('\n') +
    '\n}\n';
  return { css: cssFile, ts, kt };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render(JSON.parse(readFileSync(paths.json, 'utf8')));
  const check = process.argv.includes('--check');
  let stale = false;
  for (const k of ['css', 'ts', 'kt']) {
    if (check) {
      if (!existsSync(paths[k]) || readFileSync(paths[k], 'utf8') !== out[k]) {
        console.error(`stale: ${paths[k]}`);
        stale = true;
      }
    } else writeFileSync(paths[k], out[k]);
  }
  process.exit(stale ? 1 : 0);
}
