#!/usr/bin/env node
// The Outage mark (ADR 0053): the wordmark "outage", white on blue. One source, written to:
//   core/shared/design/icon.svg                        master picture (108 x 108 adaptive-icon box)
//   android/outage/.../res/drawable/ic_launcher_*.xml   adaptive icon layers (foreground, background, monochrome)
//   android/outage/.../res/drawable/ic_mark.xml         the blue wordmark on its own, for screens inside the app
//   web/site/logo.gen.ts                                the wordmark for the website and the favicon
// and every glyph of core/shared/design/icons.json as res/drawable/ic_sym_<name>.xml, the icons the web inlines.
// The letters are real Mona Sans outlines (OFL), stored in core/shared/design/wordmark.json.
// Dependency-free. `node tools/icon/build.mjs` writes; `--check` exits 1 when a file is stale.
// Adaptive icon rules (108 dp canvas, 66 dp safe circle): https://developer.android.com/develop/ui/views/launch/icon_design_adaptive
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const res = join(root, 'android/outage/app/src/main/res/drawable');
export const paths = {
  svg: join(root, 'core/shared/design/icon.svg'),
  fg: join(res, 'ic_launcher_foreground.xml'),
  bg: join(res, 'ic_launcher_background.xml'),
  mono: join(res, 'ic_launcher_monochrome.xml'),
  mark: join(res, 'ic_mark.xml'),
  web: join(root, 'web/site/logo.gen.ts'),
};
const ICONS = JSON.parse(readFileSync(join(root, 'core/shared/design/icons.json'), 'utf8'));
const WORD = JSON.parse(readFileSync(join(root, 'core/shared/design/wordmark.json'), 'utf8'));
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
export const symbolPath = (name) => join(res, `ic_sym_${snake(name)}.xml`);

export const COLOURS = { blue: '#1B6EF3', white: '#FFFFFF' };

// The word is 60 units wide in the 108 box, centred on the x-height, so it sits inside the 66-unit safe circle.
export const WIDTH = 60;
const X_HEIGHT = 0.52; // of the em, for Mona Sans lowercase
export function placed(width = WIDTH, cx = 54, cy = 54) {
  const s = width / WORD.advance;
  const x0 = cx - width / 2;
  const base = cy + (X_HEIGHT * WORD.unitsPerEm * s) / 2;
  return { s, x0, base };
}
/** Each glyph as [translateX, translateY, scale]: font units, y flipped. */
export function glyphs(width = WIDTH, cx = 54, cy = 54) {
  const { s, x0, base } = placed(width, cx, cy);
  return WORD.glyphs.map((g) => ({ d: g.d, tx: +(x0 + g.x * s).toFixed(3), ty: +base.toFixed(3), s: +s.toFixed(6) }));
}

const svgWord = (fill, width, cx, cy, cls) =>
  glyphs(width, cx, cy)
    .map((g) => `<path${cls ? ` class="${cls}"` : ''} transform="translate(${g.tx},${g.ty}) scale(${g.s},${-g.s})" d="${g.d}"${fill ? ` fill="${fill}"` : ''}/>`)
    .join('');

const xmlPath = (attrs) =>
  `    <path\n${Object.entries(attrs)
    .map(([k, v]) => `        android:${k}="${v}"`)
    .join('\n')} />\n`;
const argb = (hex) => `#FF${hex.slice(1).toUpperCase()}`;
const vector = (comment, body, size = 108, vw = 108, vh = 108) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment} Generated by tools/icon/build.mjs. Do not edit. -->\n` +
  `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp"\n    android:height="${Math.round((size * vh) / vw)}dp"\n` +
  `    android:viewportWidth="${vw}"\n    android:viewportHeight="${vh}">\n${body}</vector>\n`;
// Vector drawables have no transform on a path, so each glyph sits in a group.
const xmlWord = (fill, width, cx, cy) =>
  glyphs(width, cx, cy)
    .map(
      (g) =>
        `    <group\n        android:translateX="${g.tx}"\n        android:translateY="${g.ty}"\n        android:scaleX="${g.s}"\n        android:scaleY="${-g.s}">\n` +
        xmlPath({ pathData: g.d, fillColor: argb(fill) }).replace(/^ {4}/gm, '        ') +
        '    </group>\n',
    )
    .join('');

export function render() {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" role="img" aria-labelledby="t"><title id="t">Outage</title>' +
    `<rect width="108" height="108" fill="${COLOURS.blue}"/>${svgWord(COLOURS.white, WIDTH, 54, 54)}</svg>\n`;
  const fg = vector('The wordmark "outage" in white, inside the 66 dp safe zone.', xmlWord(COLOURS.white, WIDTH, 54, 54));
  const bg = vector('Blue adaptive-icon background.', xmlPath({ pathData: 'M0,0h108v108h-108z', fillColor: argb(COLOURS.blue) }));
  const mono = vector('Themed-icon layer: the wordmark in one colour; the launcher tints it.', xmlWord('#000000', WIDTH, 54, 54));
  // In-app wordmark: 120 x 32 box, blue letters.
  const mark = vector('The wordmark in blue, for the app\'s own screens.', xmlWord(COLOURS.blue, 112, 60, 16), 120, 120, 32);
  const web =
    '// Generated by tools/icon/build.mjs. Do not edit.\n' +
    `export const LOGO_SVG = ${JSON.stringify(`<svg class="wordmark" viewBox="0 0 120 32" role="img" aria-label="Outage" xmlns="http://www.w3.org/2000/svg">${svgWord(null, 112, 60, 16, 'wm')}</svg>`)};\n` +
    `export const FAVICON_SVG = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="24" fill="${COLOURS.blue}"/>${svgWord(COLOURS.white, 84, 54, 54)}</svg>`)};\n`;
  const symbols = Object.fromEntries(
    Object.entries(ICONS.icons).map(([name, d]) => [
      name,
      '<?xml version="1.0" encoding="utf-8"?>\n' +
        `<!-- ${ICONS.license} Generated by tools/icon/build.mjs from core/shared/design/icons.json. Do not edit. -->\n` +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n' +
        `    android:viewportWidth="24"\n    android:viewportHeight="24">\n${xmlPath({ pathData: d, fillColor: '#FF000000' })}</vector>\n`,
    ]),
  );
  return { svg, fg, bg, mono, mark, web, symbols };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  const check = process.argv.includes('--check');
  let stale = false;
  const files = [
    ...Object.keys(paths).map((k) => [paths[k], out[k]]),
    ...Object.entries(out.symbols).map(([name, xml]) => [symbolPath(name), xml]),
  ];
  for (const [file, text] of files) {
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
        console.error(`stale: ${file}`);
        stale = true;
      }
    } else writeFileSync(file, text);
  }
  process.exit(stale ? 1 : 0);
}
