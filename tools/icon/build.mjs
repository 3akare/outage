#!/usr/bin/env node
// The Outage mark (ADR 0048): a power symbol whose stem is a charging bolt. One geometry, written to:
//   core/shared/design/icon.svg                       master picture (108 x 108 adaptive-icon box, white background)
//   android/outage/.../res/drawable/ic_launcher_*.xml  adaptive icon layers (foreground, background, monochrome)
//   android/outage/.../res/drawable/ic_mark.xml        the mark cropped to its own box, for screens inside the app
//   web/site/logo.gen.ts                               the same mark for the website header and favicon
// and every glyph of core/shared/design/icons.json as res/drawable/ic_sym_<name>.xml, the icons the web inlines.
// Dependency-free. `node tools/icon/build.mjs` writes; `--check` exits 1 when a file is stale.
// Adaptive icon rules (108 dp canvas, 66 dp safe circle): https://developer.android.com/develop/ui/views/launch/icon_design_adaptive
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const res = join(root, 'android/outage/app/src/main/res/drawable');
export const paths = {
  svg: join(root, 'core/shared/design/icon.svg'),
  fg: join(res, 'ic_launcher_foreground.xml'),
  bg: join(res, 'ic_launcher_background.xml'),
  mono: join(res, 'ic_launcher_monochrome.xml'),
  mark: join(res, 'ic_mark.xml'),
  web: join(root, 'web/site/logo.gen.ts'),
};
const ICONS = JSON.parse(readFileSync(join(root, 'core/shared/design/icons.json'), 'utf8'));
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
export const symbolPath = (name) => join(res, `ic_sym_${snake(name)}.xml`);

// Ring: centre (54, 61), radius 18.5, stroke 7.5, open 100 degrees at the top. Three equal arcs, clockwise from the
// opening: blue, green, red. The bolt is the stem and passes through the opening. Everything sits inside the safe circle.
const C = 54;
const CY = 61;
const R = 18.5;
export const STROKE = 7.5;
const GAP = 50;
export const COLOURS = { blue: '#2F7DE1', green: '#1E9E5A', red: '#E5484D', bolt: '#F4B400', background: '#FFFFFF' };

const pt = (deg) => {
  const a = (deg * Math.PI) / 180;
  return [+(C + R * Math.cos(a)).toFixed(2), +(CY + R * Math.sin(a)).toFixed(2)];
};
const arc = (a, b) => {
  const [x1, y1] = pt(a);
  const [x2, y2] = pt(b);
  return `M${x1},${y1} A${R},${R} 0 ${b - a > 180 ? 1 : 0},1 ${x2},${y2}`;
};
const start = -90 + GAP;
const end = 270 - GAP;
const span = (end - start) / 3;
// The two end arcs have round caps. The middle arc is drawn last with flat caps and one degree of overlap, so the colour
// joins are straight cuts, like the segments of a ring.
export const SEGMENTS = [
  { d: arc(start, start + span), colour: COLOURS.blue, cap: 'round' },
  { d: arc(start + 2 * span, end), colour: COLOURS.red, cap: 'round' },
  { d: arc(start + span - 1, start + 2 * span + 1), colour: COLOURS.green, cap: 'butt' },
];
export const BOLT = 'M54.5,24.5 L62.5,24.5 L57.2,38.5 L64,38.5 L51.2,64.5 L54,47.5 L46.8,47.5 Z';

const svgBody = (mono) =>
  SEGMENTS.map(
    (s) =>
      `<path d="${s.d}" fill="none" stroke="${mono ?? s.colour}" stroke-width="${STROKE}" stroke-linecap="${s.cap}"/>`,
  ).join('') +
  `<path d="${BOLT}" fill="${mono ?? COLOURS.bolt}" stroke="${mono ?? COLOURS.bolt}" stroke-width="1.6" stroke-linejoin="round"/>`;

const xmlPath = (attrs) =>
  `    <path\n${Object.entries(attrs)
    .map(([k, v]) => `        android:${k}="${v}"`)
    .join('\n')} />\n`;
const vector = (comment, body) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment} Generated by tools/icon/build.mjs. Do not edit. -->\n` +
  '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n' +
  `    android:viewportWidth="108"\n    android:viewportHeight="108">\n${body}</vector>\n`;
const argb = (hex) => `#FF${hex.slice(1).toUpperCase()}`;

function androidLayer(mono) {
  const ring = SEGMENTS.map((s) =>
    xmlPath({
      pathData: s.d,
      strokeColor: argb(mono ?? s.colour),
      strokeWidth: String(STROKE),
      strokeLineCap: s.cap,
      fillColor: '#00000000',
    }),
  ).join('');
  const bolt = xmlPath({
    pathData: BOLT,
    fillColor: argb(mono ?? COLOURS.bolt),
    strokeColor: argb(mono ?? COLOURS.bolt),
    strokeWidth: '1.6',
    strokeLineJoin: 'round',
  });
  return ring + bolt;
}

export function render() {
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" role="img" aria-labelledby="t"><title id="t">Outage</title>' +
    `<rect width="108" height="108" fill="${COLOURS.background}"/>${svgBody()}</svg>\n`;
  const fg = vector('Outage mark: power ring with a charging-bolt stem, inside the 66 dp safe zone.', androidLayer());
  const bg = vector('White adaptive-icon background.', xmlPath({ pathData: 'M0,0h108v108h-108z', fillColor: argb(COLOURS.background) }));
  const mono = vector('Themed-icon layer: the same mark in one colour; the launcher tints it.', androidLayer('#000000'));
  // Web: the mark cropped to its own box for the header, and a favicon on a white rounded tile.
  const crop = 'viewBox="22 23 64 64"';
  const web =
    '// Generated by tools/icon/build.mjs. Do not edit.\n' +
    `export const LOGO_SVG = ${JSON.stringify(`<svg ${crop} aria-hidden="true" xmlns="http://www.w3.org/2000/svg">${svgBody()}</svg>`)};\n` +
    `export const FAVICON_SVG = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="24" fill="${COLOURS.background}"/>${svgBody()}</svg>`)};\n`;
  const mark =
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- The Outage mark cropped to its own box, for the app\'s own screens. Generated by tools/icon/build.mjs. Do not edit. -->\n' +
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="64dp"\n    android:height="64dp"\n' +
    `    android:viewportWidth="64"\n    android:viewportHeight="64">\n    <group\n        android:translateX="-22"\n        android:translateY="-23">\n${androidLayer()
      .split('\n')
      .map((l) => (l ? `    ${l}` : l))
      .join('\n')}    </group>\n</vector>\n`;
  const symbols = Object.fromEntries(
    Object.entries(ICONS.icons).map(([name, d]) => [
      name,
      '<?xml version="1.0" encoding="utf-8"?>\n' +
        `<!-- ${ICONS.license} Generated by tools/icon/build.mjs from core/shared/design/icons.json. Do not edit. -->\n` +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n' +
        `    android:viewportWidth="24"\n    android:viewportHeight="24">\n${xmlPath({ pathData: d, fillColor: '#FF000000' })}</vector>\n`,
    ]),
  );
  return { svg, fg, bg, mono, mark, web, symbols };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  const check = process.argv.includes('--check');
  let stale = false;
  const files = [
    ...Object.keys(paths).map((k) => [paths[k], out[k]]),
    ...Object.entries(out.symbols).map(([name, xml]) => [symbolPath(name), xml]),
  ];
  for (const [file, text] of files) {
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
        console.error(`stale: ${file}`);
        stale = true;
      }
    } else writeFileSync(file, text);
  }
  process.exit(stale ? 1 : 0);
}
