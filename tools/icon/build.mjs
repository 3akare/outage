#!/usr/bin/env node
// The Outage mark (ADR 0054): a disc whose left half is solid and whose right half is only a ring, power on and power
// off in one shape. One source, written to:
//   core/shared/design/icon.svg                        master picture (108 x 108 adaptive-icon box)
//   android/outage/.../res/drawable/ic_launcher_*.xml   adaptive icon layers (foreground, background, monochrome)
//   android/outage/.../res/drawable/ic_mark.xml         the mark on its own in ink, for screens inside the app
//   web/site/logo.gen.ts                                the mark for the website (currentColor) and the favicon
// and every glyph of core/shared/design/icons.json (Lucide, ISC) as res/drawable/ic_sym_<name>.xml: round 1.75 px
// strokes, the same icons the web inlines.
// Dependency-free. `node tools/icon/build.mjs` writes; `--check` exits 1 when a file is stale.
// Adaptive icon rules (108 dp canvas, 66 dp safe circle): https://developer.android.com/develop/ui/views/launch/icon_design_adaptive
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const res = join(root, 'android/outage/app/src/main/res/drawable');
export const paths = {
  svg: join(root, 'core/shared/design/icon.svg'),
  fg: join(res, 'ic_launcher_foreground.xml'),
  bg: join(res, 'ic_launcher_background.xml'),
  mono: join(res, 'ic_launcher_monochrome.xml'),
  mark: join(res, 'ic_mark.xml'),
  web: join(root, 'web/site/logo.gen.ts'),
};
const ICONS = JSON.parse(readFileSync(join(root, 'core/shared/design/icons.json'), 'utf8'));
const snake = (s) => s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
export const symbolPath = (name) => join(res, `ic_sym_${snake(name)}.xml`);

export const COLOURS = { ink: '#111113', white: '#FFFFFF' };

/** The mark's outer radius in the 108 box (inside the 33-unit safe radius) and its ring width. */
export const RADIUS = 24;
export const RING = 5.5;

/** The mark as one path centred on (cx, cy): the full disc clockwise, then the right half of the inside anticlockwise, a hole. */
export function markPath(cx = 54, cy = 54, r = RADIUS, ring = RING) {
  const f = (n) => +n.toFixed(3);
  const ri = r - ring;
  return (
    `M${f(cx)} ${f(cy - r)}A${f(r)} ${f(r)} 0 1 1 ${f(cx)} ${f(cy + r)}A${f(r)} ${f(r)} 0 1 1 ${f(cx)} ${f(cy - r)}Z` +
    `M${f(cx)} ${f(cy - ri)}L${f(cx)} ${f(cy + ri)}A${f(ri)} ${f(ri)} 0 0 0 ${f(cx)} ${f(cy - ri)}Z`
  );
}

const xmlPath = (attrs) =>
  `    <path\n${Object.entries(attrs)
    .map(([k, v]) => `        android:${k}="${v}"`)
    .join('\n')} />\n`;
const argb = (hex) => `#FF${hex.slice(1).toUpperCase()}`;
const vector = (comment, body, size = 108, vw = 108, vh = 108) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${comment} Generated by tools/icon/build.mjs. Do not edit. -->\n` +
  `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="${size}dp"\n    android:height="${Math.round((size * vh) / vw)}dp"\n` +
  `    android:viewportWidth="${vw}"\n    android:viewportHeight="${vh}">\n${body}</vector>\n`;

export function render() {
  const d = markPath();
  const svg =
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" role="img" aria-labelledby="t"><title id="t">Outage</title>' +
    `<rect width="108" height="108" fill="${COLOURS.ink}"/><path fill="${COLOURS.white}" d="${d}"/></svg>\n`;
  const fg = vector('The mark in white, inside the 66 dp safe zone.', xmlPath({ pathData: d, fillColor: argb(COLOURS.white) }));
  const bg = vector('Ink adaptive-icon background.', xmlPath({ pathData: 'M0,0h108v108h-108z', fillColor: argb(COLOURS.ink) }));
  const mono = vector('Themed-icon layer: the mark in one colour; the launcher tints it.', xmlPath({ pathData: d, fillColor: '#FF000000' }));
  // In-app mark: a 24 dp square in ink; Compose can tint it.
  const mark = vector('The mark in ink, for the app\'s own screens.', xmlPath({ pathData: markPath(12, 12, 11, 2.5), fillColor: argb(COLOURS.ink) }), 24, 24, 24);
  const web =
    '// Generated by tools/icon/build.mjs. Do not edit.\n' +
    `export const LOGO_SVG = ${JSON.stringify(`<svg class="mark" viewBox="0 0 24 24" aria-hidden="true" xmlns="http://www.w3.org/2000/svg"><path fill="currentColor" d="${markPath(12, 12, 11, 2.5)}"/></svg>`)};\n` +
    `export const FAVICON_SVG = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><rect width="108" height="108" rx="24" fill="${COLOURS.ink}"/><path fill="${COLOURS.white}" d="${markPath(54, 54, 30, 7)}"/></svg>`)};\n`;
  const symbols = Object.fromEntries(
    Object.entries(ICONS.icons).map(([name, pd]) => [
      name,
      '<?xml version="1.0" encoding="utf-8"?>\n' +
        `<!-- ${ICONS.license} Generated by tools/icon/build.mjs from core/shared/design/icons.json. Do not edit. -->\n` +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n' +
        `    android:viewportWidth="24"\n    android:viewportHeight="24">\n` +
        xmlPath({
          pathData: pd,
          fillColor: '#00000000',
          strokeColor: '#FF000000',
          strokeWidth: String(ICONS.stroke),
          strokeLineCap: 'round',
          strokeLineJoin: 'round',
        }) +
        '</vector>\n',
    ]),
  );
  return { svg, fg, bg, mono, mark, web, symbols };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = render();
  const check = process.argv.includes('--check');
  let stale = false;
  const files = [
    ...Object.keys(paths).map((k) => [paths[k], out[k]]),
    ...Object.entries(out.symbols).map(([name, xml]) => [symbolPath(name), xml]),
  ];
  for (const [file, text] of files) {
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
        console.error(`stale: ${file}`);
        stale = true;
      }
    } else writeFileSync(file, text);
  }
  process.exit(stale ? 1 : 0);
}
